"""Fast, cached research overview data for the cockpit home screen.

The dashboard catalog is intentionally built out of the request path. It is a
large read model and may be regenerated by the CLI; the cockpit only needs a
small, evidence-labelled slice for the home screen.
"""

from __future__ import annotations

import json
import threading
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from open_composer.cockpit.data.paper import AccountEquityHistory, build_account_equity_history


@dataclass(frozen=True)
class EvidenceRow:
    name: str
    lifecycle: str
    model_role: str
    factor_count: int
    research_status: str
    paper_status: str
    latest_sharpe: float | None
    latest_return_pct: float | None
    evidence_level: str | None
    blocker: str | None


@dataclass(frozen=True)
class ResearchOverview:
    generated_at: datetime | None = None
    catalog_at: datetime | None = None
    stale: bool = True
    loading: bool = True
    strategy_count: int = 0
    factor_count: int = 0
    model_count: int = 0
    model_roles: dict[str, int] = field(default_factory=dict)
    feature_packet_count: int = 0
    alternative_data_report_count: int = 0
    market_timing_report_count: int = 0
    paper_strategy_count: int = 0
    research_run_count: int = 0
    research_blocked_count: int = 0
    paper_readiness_counts: dict[str, int] = field(default_factory=dict)
    rows: tuple[EvidenceRow, ...] = ()
    warning: str | None = None


def _number(value: Any) -> float | None:
    return value if isinstance(value, (int, float)) and not isinstance(value, bool) else None


def _gate_code(value: Any, fallback: Any = None) -> str:
    value = fallback if value is None else value
    if value is True or value == "ok":
        return "pass"
    if value is False or value in {"blocked", "fail", "warning"}:
        return "blocked" if value == "blocked" or value is False else "warning"
    return "unknown"


def _parse_datetime(value: Any) -> datetime | None:
    if not isinstance(value, str):
        return None
    try:
        return datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError:
        return None


def _catalog_at(payload: dict[str, Any]) -> datetime | None:
    return _parse_datetime(payload.get("generated_at")) or _parse_datetime(
        (payload.get("summary") or {}).get("generated_at")
    )


def _build_overview(payload: dict[str, Any], *, catalog_mtime: datetime) -> ResearchOverview:
    summary = payload.get("summary") if isinstance(payload.get("summary"), dict) else {}
    strategies = [item for item in payload.get("strategies", []) if isinstance(item, dict)]
    runs = [item for item in payload.get("runs", []) if isinstance(item, dict)]
    readiness = [
        item for item in payload.get("paper_readiness_reports", []) if isinstance(item, dict)
    ]
    latest_run: dict[str, dict[str, Any]] = {}
    for run in runs:
        name = run.get("strategy_name")
        if not isinstance(name, str):
            continue
        previous = latest_run.get(name)
        stamp = _parse_datetime(run.get("last_signal_at")) or _parse_datetime(
            run.get("first_signal_at")
        )
        previous_stamp = _parse_datetime(previous.get("last_signal_at")) if previous else None
        if previous is None or (
            stamp is not None and (previous_stamp is None or stamp > previous_stamp)
        ):
            latest_run[name] = run

    paper_by_name = {item.get("strategy_name"): item for item in readiness}
    selected = [
        item
        for item in strategies
        if item.get("overview_selected") or item.get("lifecycle") in {"active", "approved"}
    ][:12]
    rows: list[EvidenceRow] = []
    for strategy in selected:
        name = str(strategy.get("strategy_name", "unknown"))
        run = latest_run.get(name, {})
        paper = paper_by_name.get(name, {})
        gate = paper.get("gate_summary") if isinstance(paper.get("gate_summary"), dict) else {}
        blocked = gate.get("blocked_checks") or paper.get("blocking_checks") or []
        rows.append(
            EvidenceRow(
                name=name,
                lifecycle=str(strategy.get("lifecycle", "unknown")),
                model_role=str(strategy.get("model_role", "unknown")),
                factor_count=int(strategy.get("factor_count") or 0),
                research_status=_gate_code(gate.get("research_pass")),
                paper_status=_gate_code(gate.get("paper_ready_pass"), paper.get("status")),
                latest_sharpe=_number(run.get("sharpe_ratio")),
                latest_return_pct=_number(run.get("total_return_pct")),
                evidence_level=(
                    run.get("evidence_level")
                    if isinstance(run.get("evidence_level"), str)
                    else None
                ),
                blocker=str(blocked[0]) if blocked else None,
            )
        )

    model_roles = (
        summary.get("model_role_counts")
        if isinstance(summary.get("model_role_counts"), dict)
        else {}
    )
    research_reports = [
        item for item in payload.get("research_reports", []) if isinstance(item, dict)
    ]
    paper_names = {
        item.get("strategy_name")
        for item in strategies
        if item.get("overview_selected") and item.get("lifecycle") not in {"active", "approved"}
    }
    is_stale = (datetime.now(UTC) - catalog_mtime).total_seconds() > 86400
    return ResearchOverview(
        generated_at=datetime.now(UTC),
        catalog_at=_catalog_at(payload),
        stale=is_stale,
        loading=False,
        strategy_count=int(summary.get("strategy_count") or 0),
        factor_count=int(summary.get("factor_count") or 0),
        model_count=sum(
            int(value or 0)
            for role, value in model_roles.items()
            if role not in {"pure_quant", "unknown"}
        ),
        model_roles={str(key): int(value or 0) for key, value in model_roles.items()},
        feature_packet_count=int(summary.get("feature_packet_count") or 0),
        alternative_data_report_count=int(
            summary.get("alternative_data_report_count")
            or sum(
                1 for item in research_reports if item.get("kind") == "alternative_data_evidence"
            )
        ),
        market_timing_report_count=int(
            summary.get("market_timing_report_count")
            or sum(1 for item in research_reports if item.get("kind") == "market_timing")
        ),
        paper_strategy_count=len({name for name in paper_names if isinstance(name, str)}),
        research_run_count=int(summary.get("research_run_count") or 0),
        research_blocked_count=int(summary.get("research_blocked_count") or 0),
        paper_readiness_counts={
            str(key): int(value or 0)
            for key, value in (summary.get("paper_readiness_status_counts") or {}).items()
        },
        rows=tuple(rows),
        warning="catalog read model is stale" if is_stale else None,
    )


def write_overview_snapshot(catalog_path: Path, output_path: Path) -> Path:
    """Write the compact request-safe slice from a full catalog artifact."""
    with catalog_path.open("r", encoding="utf-8") as handle:
        payload = json.load(handle)
    if not isinstance(payload, dict):
        raise ValueError("catalog root is not an object")
    summary = payload.get("summary") if isinstance(payload.get("summary"), dict) else {}
    all_strategies = [item for item in payload.get("strategies", []) if isinstance(item, dict)]
    readiness = [
        item for item in payload.get("paper_readiness_reports", []) if isinstance(item, dict)
    ]
    observed_paper_names = {
        item.get("strategy_name")
        for item in payload.get("runs", [])
        if isinstance(item, dict)
        and item.get("kind") == "paper"
        and isinstance(item.get("strategy_name"), str)
    }
    rehearsal_dir = catalog_path.parent.parent / "paper" / "rehearsal"
    observed_paper_names.update(
        path.name[: -len("-latest.json")] for path in rehearsal_dir.glob("*-latest.json")
    )
    selected_names: set[str] = {
        str(item.get("strategy_name"))
        for item in all_strategies
        if item.get("lifecycle") in {"active", "approved"}
    }
    selected_names.update(name for name in observed_paper_names if isinstance(name, str))
    strategies = [
        {**item, "overview_selected": True}
        for item in all_strategies
        if item.get("strategy_name") in selected_names
    ]
    names = {item.get("strategy_name") for item in strategies}
    runs = [
        item
        for item in payload.get("runs", [])
        if isinstance(item, dict) and item.get("strategy_name") in names
    ]
    latest: dict[str, dict[str, Any]] = {}
    for run in runs:
        name = run.get("strategy_name")
        if not isinstance(name, str):
            continue
        stamp = run.get("last_signal_at") or run.get("first_signal_at") or ""
        previous = latest.get(name)
        previous_stamp = (
            previous.get("last_signal_at") or previous.get("first_signal_at") or ""
            if previous
            else ""
        )
        if previous is None or stamp > previous_stamp:
            latest[name] = run
    compact_summary = dict(summary)
    research_reports = [
        item for item in payload.get("research_reports", []) if isinstance(item, dict)
    ]
    compact_summary["alternative_data_report_count"] = sum(
        1 for item in research_reports if item.get("kind") == "alternative_data_evidence"
    )
    compact_summary["market_timing_report_count"] = sum(
        1 for item in research_reports if item.get("kind") == "market_timing"
    )
    compact = {
        "generated_at": datetime.now(UTC).isoformat(),
        "summary": compact_summary,
        "strategies": strategies,
        "runs": list(latest.values()),
        "paper_readiness_reports": [
            item for item in readiness if item.get("strategy_name") in names
        ],
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(compact, ensure_ascii=False), encoding="utf-8")
    return output_path


class ResearchOverviewCache:
    def __init__(self) -> None:
        self._value = ResearchOverview()
        self._lock = threading.Lock()

    def get(self) -> ResearchOverview:
        with self._lock:
            return self._value

    def refresh(self, root: Path) -> ResearchOverview:
        path = root / "reports" / "dashboard" / "overview.json"
        try:
            stat = path.stat()
            with path.open("r", encoding="utf-8") as handle:
                payload = json.load(handle)
            if not isinstance(payload, dict):
                raise ValueError("overview root is not an object")
            value = _build_overview(
                payload,
                catalog_mtime=datetime.fromtimestamp(stat.st_mtime, tz=UTC),
            )
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            value = ResearchOverview(
                loading=False,
                warning=f"overview snapshot unavailable: {type(exc).__name__}",
            )
        with self._lock:
            self._value = value
            return value


_DEFAULT_CACHE = ResearchOverviewCache()


def get_default_research_overview_cache() -> ResearchOverviewCache:
    return _DEFAULT_CACHE


class PaperEquityCache:
    def __init__(self) -> None:
        self._value: AccountEquityHistory | None = None
        self._lock = threading.Lock()

    def get(self) -> AccountEquityHistory | None:
        with self._lock:
            return self._value

    def refresh(self, root: Path) -> AccountEquityHistory:
        value = build_account_equity_history(root)
        with self._lock:
            self._value = value
            return value


_DEFAULT_EQUITY_CACHE = PaperEquityCache()


def get_default_paper_equity_cache() -> PaperEquityCache:
    return _DEFAULT_EQUITY_CACHE


