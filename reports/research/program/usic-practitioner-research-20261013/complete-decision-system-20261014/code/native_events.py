"""Declared OHLC scenario -> synthetic native book data; no matching engine.

Synthetic locked quotes and volume/4 depth are conditional fill assumptions,
never actual NBBO, auction, displayed liquidity or universal NAV bounds.
"""

import math
from datetime import datetime
from itertools import groupby

import msgspec
from nautilus_policy_adapter import MartinBoundaryData
from nautilus_trader.model.data import (
    BookOrder,
    CustomData,
    DataType,
    OrderBookDelta,
    OrderBookDeltas,
    QuoteTick,
)
from nautilus_trader.model.enums import BookAction, OrderSide
from nautilus_trader.model.identifiers import InstrumentId
from nautilus_trader.model.objects import Price, Quantity

SCENARIOS = {
    "O-H-L-C": ("open", "high", "low", "close"),
    "O-L-H-C": ("open", "low", "high", "close"),
}


def boundary(stage, ns, packet, rows):
    data = MartinBoundaryData(
        stage=stage,
        frames_json=msgspec.json.encode(rows).decode(),
        session_ordinal=packet["ordinal"],
        month=packet["session"][:7],
        ts_event=ns,
        ts_init=ns,
    )
    return CustomData(DataType(MartinBoundaryData), data)


def native_month(packets, scenario, initial_factors, trigger_masks=None, *, active_symbols=None):
    """Build an interval from the already-known causal activity envelope.

    None retains the original full feed. Inactive symbols have no possible
    orders/positions in this interval. Their four prices still reach the
    controller at precisely the original quote timestamps, as one grouped
    custom mark event per point. Active native L2 books, volume, quotes and all
    other phases are byte-for-byte generated by the original branch.
    """
    fields = SCENARIOS[scenario]
    factors = dict(initial_factors)
    books = []
    quotes = []
    boundaries = []
    for packet in packets:
        inactive_marks = {}
        excluded = (trigger_masks or {}).get(packet["session"], {})
        frames = [
            dict(r, frame=dict(r["frame"], trigger_price_eligible=False))
            if excluded.get(r["frame"]["symbol"]) is False
            else r
            for r in packet["frames"]
        ]
        ns = int(datetime.fromisoformat(packet["start"]).timestamp() * 1e9)
        if packet["minute"] == 0:
            if packet["actions"]:
                boundaries.append(boundary("actions", ns, packet, packet["actions"]))
                for a in packet["actions"]:
                    if a["kind"] == "forward_split":
                        factors[a["symbol"]] = factors.get(a["symbol"], 1.0) * a["ratio"]
        if packet["missing"]:
            boundaries.append(boundary("missing", ns + 2, packet, packet["missing"]))
        for row in sorted(packet["prices"], key=lambda r: r["symbol"]):
            symbol = row["symbol"]
            factor = factors.get(symbol, 1.0)
            id = InstrumentId.from_str(symbol + ".SIM")
            physical_depth = math.floor(row["volume"] / 4)
            if physical_depth <= 0:
                boundaries.append(boundary("missing", ns + 2, packet, [symbol]))
                continue
            native_depth = physical_depth / factor
            if not float(native_depth).is_integer():
                raise ValueError("unrepresentable physical depth coordinate")
            for offset, field in zip(
                (3, 20_000_000_000, 40_000_000_000, 59_999_999_995), fields, strict=True
            ):
                ts = ns + offset
                price = Price(row[field] * factor, 4)
                if active_symbols is not None and symbol not in active_symbols:
                    inactive_marks.setdefault(ts + 1, []).append(
                        dict(symbol=symbol, price=price.as_double() / factor)
                    )
                    continue
                qty = Quantity.from_int(int(native_depth))
                books.append(
                    OrderBookDeltas(
                        id,
                        [
                            OrderBookDelta(id, BookAction.CLEAR, None, 0, 0, ts, ts),
                            OrderBookDelta(
                                id,
                                BookAction.ADD,
                                BookOrder(OrderSide.BUY, price, qty, 1),
                                0,
                                0,
                                ts,
                                ts,
                            ),
                            OrderBookDelta(
                                id,
                                BookAction.ADD,
                                BookOrder(OrderSide.SELL, price, qty, 2),
                                128,
                                0,
                                ts,
                                ts,
                            ),
                        ],
                    )
                )
                quotes.append(QuoteTick(id, price, price, qty, qty, ts + 1, ts + 1))
        for ts, rows in inactive_marks.items():
            boundaries.append(boundary("inactive_marks", ts, packet, rows))
        boundaries.extend(
            [
                boundary("open_exits", ns + 6, packet, []),
                boundary("open_entries", ns + 7, packet, []),
                boundary(
                    "mark",
                    ns + 59_999_999_998,
                    packet,
                    dict(daily_close=packet["minute"] + 1 == packet["session_minutes"]),
                ),
                boundary("close", ns + 60_000_000_001, packet, frames),
            ]
        )
    return books, quotes, boundaries, factors


def causal_activity(strategy, first_packet, *, afternoon):
    """Only present state and context known before this interval may prune.

    Missing first-minute Frames or context not yet available fail open to the
    full morning universe. All native positions/orders and staged intents are
    retained, even if they disagree with the policy state. After the entry
    cutoff no flat name can create a buy; existing pending orders remain.
    """
    active = {
        s
        for s, st in strategy.policy.states.items()
        if st.quantity or st.pending or st.pending_exit or st.protective
    }
    active.update(p.instrument_id.symbol.value for p in strategy.cache.positions_open())
    active.update(o.instrument_id.symbol.value for o in strategy.cache.orders_open())
    for mapping in (strategy.staged_entries, strategy.staged_exits, strategy.cancel_then_sell):
        active.update(i.symbol for i in mapping.values())
    if afternoon:
        assert first_packet["minute"] > strategy.config.parameters["entry_cutoff_minute"]
        return active
    # Leadership is frozen from daily prior-session context for the full day.
    # Use only Frames already consumed at a prior close. A missing completion
    # is not evidence of ineligibility; the opening prefix keeps all symbols.
    active.update(strategy.ids)
    start = datetime.fromisoformat(first_packet["start"])
    for symbol, (session, possible_entry, end) in strategy.runtime_prior_leadership.items():
        if session == first_packet["session"] and end <= start and not possible_entry:
            active.discard(symbol)
    # Held/pending names must override the daily leadership exclusion.
    active.update(
        s
        for s, st in strategy.policy.states.items()
        if st.quantity or st.pending or st.pending_exit or st.protective
    )
    active.update(p.instrument_id.symbol.value for p in strategy.cache.positions_open())
    active.update(o.instrument_id.symbol.value for o in strategy.cache.orders_open())
    for mapping in (strategy.staged_entries, strategy.staged_exits, strategy.cancel_then_sell):
        active.update(i.symbol for i in mapping.values())
    return active


def source_intervals(packets, cutoff):
    """Opening prefix, morning, afternoon; ending120 executes at open120."""
    for _, group in groupby(packets, key=lambda p: p["session"]):
        day = list(group)
        prefix = [p for p in day if p["minute"] < 2]
        morning = [p for p in day if 2 <= p["minute"] <= cutoff]
        afternoon = [p for p in day if p["minute"] > cutoff]
        if prefix:
            yield prefix, False
        if morning:
            yield morning, False
        if afternoon:
            yield afternoon, True
